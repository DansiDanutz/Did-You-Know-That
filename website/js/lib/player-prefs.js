// Episode player preferences: mute and caption language. Pure helpers shared by the page template
// (tools/lib/components.mjs) and the browser (js/ui/player.js). Stored only in this browser.
//
// What the language choice does (checked against YouTube, Oct 2026): the narration stays English.
// For any other language the player turns on captions and asks YouTube to auto-translate the English
// captions (player API setOption("captions", "track", { translationLanguage })). URL parameters on
// their own (cc_lang_pref / hl) only switch YouTube's menus; they do not translate the captions.

export const STORAGE_KEY = "dyk-player-v1";
export const DEFAULT_LANGUAGE = "en";

/** Language choices, in the order the picker shows them. */
export const LANGUAGES = Object.freeze([
  Object.freeze({ code: "en", label: "English" }),
  Object.freeze({ code: "ro", label: "Română" }),
  Object.freeze({ code: "de", label: "Deutsch" }),
  Object.freeze({ code: "es", label: "Español" }),
  Object.freeze({ code: "fr", label: "Français" }),
  Object.freeze({ code: "it", label: "Italiano" }),
  Object.freeze({ code: "pt", label: "Português" }),
]);

const CODES = new Set(LANGUAGES.map((language) => language.code));

export const normalizeLanguage = (code) => (CODES.has(code) ? code : DEFAULT_LANGUAGE);
export const languageLabel = (code) => LANGUAGES.find((language) => language.code === normalizeLanguage(code)).label;
export const wantsCaptions = (code) => normalizeLanguage(code) !== DEFAULT_LANGUAGE;

export const DEFAULT_PREFS = Object.freeze({ muted: false, language: DEFAULT_LANGUAGE });

/** Any stored value → a valid { muted, language } (unknown or broken data → defaults). */
export function normalizePrefs(value) {
  const source = value && typeof value === "object" ? value : {};
  return Object.freeze({ muted: source.muted === true, language: normalizeLanguage(source.language) });
}

/**
 * The iframe src for a youtube-nocookie embed base URL. English: no forced captions. Any other
 * language: captions on, YouTube's menus in that language. `origin` lets the page talk to the player;
 * `start` (seconds) resumes from where a re-created player left off.
 */
export function playerSrc(base, { language = DEFAULT_LANGUAGE, muted = false, autoplay = true, origin = "", start = 0 } = {}) {
  const url = new URL(base);
  if (url.hostname !== "www.youtube-nocookie.com") throw new Error(`Not a youtube-nocookie embed: ${base}`);
  const params = url.searchParams;
  if (autoplay) params.set("autoplay", "1");
  params.set("rel", "0");
  params.set("modestbranding", "1");
  params.set("enablejsapi", "1");
  if (origin) params.set("origin", origin);
  if (muted) params.set("mute", "1");
  const seconds = Math.floor(Number(start));
  if (seconds > 0) params.set("start", String(seconds));
  const code = normalizeLanguage(language);
  if (wantsCaptions(code)) {
    params.set("cc_load_policy", "1");
    params.set("cc_lang_pref", code);
    params.set("hl", code);
  }
  return url.href;
}

/**
 * The captions track to ask the player for: a real track in that language when the video has one,
 * otherwise the English (auto-generated by default) track auto-translated into it. English → null.
 */
export function captionTrackFor(language, tracklist = []) {
  const code = normalizeLanguage(language);
  if (!wantsCaptions(code)) return null;
  const tracks = Array.isArray(tracklist) ? tracklist : [];
  const own = tracks.find((track) => track?.languageCode === code);
  if (own) return { languageCode: code };
  const english = tracks.find((track) => track?.languageCode?.startsWith("en"));
  return {
    languageCode: english?.languageCode ?? "en",
    kind: english ? english.kind ?? "" : "asr",
    translationLanguage: { languageCode: code },
  };
}

/** A command for the player iframe (the message format the YouTube IFrame API itself sends). */
export const playerCommand = (func, args = []) => JSON.stringify({ event: "command", func, args, id: 1, channel: "widget" });

/** Read saved prefs; blocked or broken storage → defaults. */
export function loadPrefs(getStorage = () => globalThis.localStorage) {
  try {
    const stored = getStorage()?.getItem(STORAGE_KEY);
    return normalizePrefs(stored ? JSON.parse(stored) : null);
  } catch {
    return DEFAULT_PREFS;
  }
}

/** Save prefs; returns the normalized prefs (storage failures are ignored: the choice lasts this visit). */
export function savePrefs(prefs, getStorage = () => globalThis.localStorage) {
  const clean = normalizePrefs(prefs);
  try {
    getStorage()?.setItem(STORAGE_KEY, JSON.stringify(clean));
  } catch {
    // Private mode or disabled storage: keep the choice in memory only.
  }
  return clean;
}
